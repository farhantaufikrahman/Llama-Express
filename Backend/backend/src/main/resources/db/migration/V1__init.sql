-- ---------- USERS ----------
CREATE TABLE users (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    role            VARCHAR2(20 CHAR)  NOT NULL,
    full_name       VARCHAR2(100 CHAR) NOT NULL,
    email           VARCHAR2(150 CHAR) NOT NULL,
    phone           VARCHAR2(20 CHAR)  NOT NULL,
    password_hash   VARCHAR2(100 CHAR) NOT NULL,
    status          VARCHAR2(20 CHAR)  DEFAULT 'ACTIVE' NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_users        PRIMARY KEY (id),
    CONSTRAINT uq_users_email  UNIQUE (email),
    CONSTRAINT uq_users_phone  UNIQUE (phone),
    CONSTRAINT ck_users_role   CHECK (role IN ('CUSTOMER','COURIER','ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE','SUSPENDED'))
);

-- ---------- COURIER PROFILES (1:1 dengan users) ----------
CREATE TABLE courier_profiles (
    user_id             NUMBER(19)        NOT NULL,
    vehicle_type        VARCHAR2(10 CHAR) NOT NULL,
    plate_number        VARCHAR2(15 CHAR) NOT NULL,
    license_no          VARCHAR2(30 CHAR),
    verification_status VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    is_online           BOOLEAN           DEFAULT FALSE NOT NULL,
    rating_avg          NUMBER(3,2)       DEFAULT 0 NOT NULL,
    rating_count        NUMBER(10)        DEFAULT 0 NOT NULL,
    created_at          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_courier_profiles PRIMARY KEY (user_id),
    CONSTRAINT fk_cp_user     FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_cp_plate    UNIQUE (plate_number),
    CONSTRAINT ck_cp_vehicle  CHECK (vehicle_type IN ('MOTOR','CAR')),
    CONSTRAINT ck_cp_verif    CHECK (verification_status IN ('PENDING','VERIFIED','REJECTED')),
    CONSTRAINT ck_cp_rating   CHECK (rating_avg BETWEEN 0 AND 5)
);

-- ---------- ADDRESSES ----------
CREATE TABLE addresses (
    id            NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id       NUMBER(19)         NOT NULL,
    label         VARCHAR2(50 CHAR)  NOT NULL,
    address_line  VARCHAR2(255 CHAR) NOT NULL,
    lat           NUMBER(9,6)        NOT NULL,
    lng           NUMBER(9,6)        NOT NULL,
    notes         VARCHAR2(255 CHAR),
    created_at    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_addresses   PRIMARY KEY (id),
    CONSTRAINT fk_addr_user   FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_addr_user ON addresses (user_id);

-- ---------- TARIFFS ----------
CREATE TABLE tariffs (
    id            NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    service_type  VARCHAR2(20 CHAR) NOT NULL,
    vehicle_type  VARCHAR2(10 CHAR) NOT NULL,
    base_fare     NUMBER(12,2)      NOT NULL,
    per_km_fare   NUMBER(12,2)      NOT NULL,
    min_fare      NUMBER(12,2)      NOT NULL,
    active_from   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    active_to     TIMESTAMP(6) WITH TIME ZONE,
    created_at    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_tariffs        PRIMARY KEY (id),
    CONSTRAINT ck_tariff_service CHECK (service_type IN ('INSTANT','SAME_DAY')),
    CONSTRAINT ck_tariff_vehicle CHECK (vehicle_type IN ('MOTOR','CAR')),
    CONSTRAINT ck_tariff_amounts CHECK (base_fare >= 0 AND per_km_fare >= 0 AND min_fare >= 0)
);
CREATE INDEX ix_tariff_lookup ON tariffs (service_type, vehicle_type, active_from);

-- ---------- ORDERS ----------
CREATE TABLE orders (
    id                 NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_code         VARCHAR2(20 CHAR)  NOT NULL,
    tracking_token     VARCHAR2(64 CHAR)  NOT NULL,
    customer_id        NUMBER(19)         NOT NULL,
    courier_id         NUMBER(19),
    service_type       VARCHAR2(20 CHAR)  NOT NULL,
    vehicle_type       VARCHAR2(10 CHAR)  NOT NULL,
    item_category      VARCHAR2(20 CHAR)  NOT NULL,
    item_desc          VARCHAR2(255 CHAR),
    weight_kg          NUMBER(6,2),
    pickup_address     VARCHAR2(255 CHAR) NOT NULL,
    pickup_lat         NUMBER(9,6)        NOT NULL,
    pickup_lng         NUMBER(9,6)        NOT NULL,
    dropoff_address    VARCHAR2(255 CHAR) NOT NULL,
    dropoff_lat        NUMBER(9,6)        NOT NULL,
    dropoff_lng        NUMBER(9,6)        NOT NULL,
    recipient_name     VARCHAR2(100 CHAR) NOT NULL,
    recipient_phone    VARCHAR2(20 CHAR)  NOT NULL,
    notes              VARCHAR2(500 CHAR),
    distance_m         NUMBER(10)         NOT NULL,
    price_total        NUMBER(12,2)       NOT NULL,
    payment_method     VARCHAR2(20 CHAR)  NOT NULL,
    payment_status     VARCHAR2(20 CHAR)  DEFAULT 'UNPAID' NOT NULL,
    status             VARCHAR2(30 CHAR)  DEFAULT 'CREATED' NOT NULL,
    verification_code  VARCHAR2(6 CHAR)   NOT NULL,
    version            NUMBER(19)         DEFAULT 0 NOT NULL,
    created_at         TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at         TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    assigned_at        TIMESTAMP(6) WITH TIME ZONE,
    picked_up_at       TIMESTAMP(6) WITH TIME ZONE,
    delivered_at       TIMESTAMP(6) WITH TIME ZONE,
    cancelled_at       TIMESTAMP(6) WITH TIME ZONE,
    cancel_reason      VARCHAR2(255 CHAR),
    CONSTRAINT pk_orders           PRIMARY KEY (id),
    CONSTRAINT uq_orders_code      UNIQUE (order_code),
    CONSTRAINT uq_orders_track     UNIQUE (tracking_token),
    CONSTRAINT fk_orders_customer  FOREIGN KEY (customer_id) REFERENCES users (id),
    CONSTRAINT fk_orders_courier   FOREIGN KEY (courier_id)  REFERENCES users (id),
    CONSTRAINT ck_orders_service   CHECK (service_type IN ('INSTANT','SAME_DAY')),
    CONSTRAINT ck_orders_vehicle   CHECK (vehicle_type IN ('MOTOR','CAR')),
    CONSTRAINT ck_orders_item      CHECK (item_category IN ('DOCUMENT','FOOD','GOODS')),
    CONSTRAINT ck_orders_paymethod CHECK (payment_method IN ('CASH','MIDTRANS')),
    CONSTRAINT ck_orders_paystatus CHECK (payment_status IN ('UNPAID','PENDING','PAID','FAILED','REFUNDED')),
    CONSTRAINT ck_orders_status    CHECK (status IN ('CREATED','SEARCHING_COURIER','ASSIGNED','PICKING_UP',
                                                     'PICKED_UP','IN_TRANSIT','DELIVERED','CANCELLED','FAILED'))
);
CREATE INDEX ix_orders_customer ON orders (customer_id, created_at);
CREATE INDEX ix_orders_courier  ON orders (courier_id, status);
CREATE INDEX ix_orders_status   ON orders (status, created_at);

-- ---------- ORDER STATUS HISTORY ----------
CREATE TABLE order_status_history (
    id           NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_id     NUMBER(19)        NOT NULL,
    from_status  VARCHAR2(30 CHAR),
    to_status    VARCHAR2(30 CHAR) NOT NULL,
    actor_id     NUMBER(19),
    note         VARCHAR2(255 CHAR),
    occurred_at  TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_osh       PRIMARY KEY (id),
    CONSTRAINT fk_osh_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_osh_actor FOREIGN KEY (actor_id) REFERENCES users (id)
);
CREATE INDEX ix_osh_order ON order_status_history (order_id, occurred_at);

-- ---------- ORDER OFFERS (tawaran ke kurir) ----------
CREATE TABLE order_offers (
    id            NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_id      NUMBER(19)        NOT NULL,
    courier_id    NUMBER(19)        NOT NULL,
    status        VARCHAR2(20 CHAR) DEFAULT 'OFFERED' NOT NULL,
    offered_at    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    expires_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    responded_at  TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_offers          PRIMARY KEY (id),
    CONSTRAINT fk_offers_order    FOREIGN KEY (order_id)   REFERENCES orders (id),
    CONSTRAINT fk_offers_courier  FOREIGN KEY (courier_id) REFERENCES users (id),
    CONSTRAINT uq_offers_pair     UNIQUE (order_id, courier_id),
    CONSTRAINT ck_offers_status   CHECK (status IN ('OFFERED','ACCEPTED','REJECTED','EXPIRED'))
);
CREATE INDEX ix_offers_courier ON order_offers (courier_id, status);

-- ---------- COURIER LOCATIONS (histori; posisi live ada di Redis) ----------
CREATE TABLE courier_locations (
    id           NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    courier_id   NUMBER(19)  NOT NULL,
    order_id     NUMBER(19),
    lat          NUMBER(9,6) NOT NULL,
    lng          NUMBER(9,6) NOT NULL,
    speed        NUMBER(6,2),
    heading      NUMBER(5,2),
    recorded_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_cloc         PRIMARY KEY (id),
    CONSTRAINT fk_cloc_courier FOREIGN KEY (courier_id) REFERENCES users (id),
    CONSTRAINT fk_cloc_order   FOREIGN KEY (order_id)   REFERENCES orders (id)
);
CREATE INDEX ix_cloc_order   ON courier_locations (order_id, recorded_at);
CREATE INDEX ix_cloc_courier ON courier_locations (courier_id, recorded_at);

-- ---------- PROOF OF DELIVERY (foto di Cloudinary) ----------
CREATE TABLE proofs_of_delivery (
    id               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_id         NUMBER(19)         NOT NULL,
    photo_url        VARCHAR2(500 CHAR) NOT NULL,
    photo_public_id  VARCHAR2(255 CHAR) NOT NULL,
    received_by      VARCHAR2(100 CHAR),
    captured_at      TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_pod       PRIMARY KEY (id),
    CONSTRAINT uq_pod_order UNIQUE (order_id),
    CONSTRAINT fk_pod_order FOREIGN KEY (order_id) REFERENCES orders (id)
);

-- ---------- PAYMENTS (transaksi Midtrans) ----------
CREATE TABLE payments (
    id                 NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_id           NUMBER(19)         NOT NULL,
    provider           VARCHAR2(20 CHAR)  DEFAULT 'MIDTRANS' NOT NULL,
    merchant_order_id  VARCHAR2(50 CHAR)  NOT NULL,
    transaction_id     VARCHAR2(64 CHAR),
    payment_type       VARCHAR2(30 CHAR),
    amount             NUMBER(12,2)       NOT NULL,
    status             VARCHAR2(20 CHAR)  DEFAULT 'PENDING' NOT NULL,
    snap_token         VARCHAR2(100 CHAR),
    redirect_url       VARCHAR2(500 CHAR),
    raw_notification   CLOB,
    paid_at            TIMESTAMP(6) WITH TIME ZONE,
    created_at         TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at         TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_payments          PRIMARY KEY (id),
    CONSTRAINT uq_payments_merchant UNIQUE (merchant_order_id),
    CONSTRAINT fk_payments_order    FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT ck_payments_provider CHECK (provider IN ('MIDTRANS')),
    CONSTRAINT ck_payments_status   CHECK (status IN ('PENDING','PAID','FAILED','EXPIRED','REFUNDED')),
    CONSTRAINT ck_payments_json     CHECK (raw_notification IS JSON)
);
CREATE INDEX ix_payments_order ON payments (order_id);

-- ---------- RATINGS ----------
CREATE TABLE ratings (
    id           NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_id     NUMBER(19) NOT NULL,
    customer_id  NUMBER(19) NOT NULL,
    courier_id   NUMBER(19) NOT NULL,
    score        NUMBER(1)  NOT NULL,
    review       VARCHAR2(500 CHAR),
    created_at   TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_ratings          PRIMARY KEY (id),
    CONSTRAINT uq_ratings_order    UNIQUE (order_id),
    CONSTRAINT fk_ratings_order    FOREIGN KEY (order_id)    REFERENCES orders (id),
    CONSTRAINT fk_ratings_customer FOREIGN KEY (customer_id) REFERENCES users (id),
    CONSTRAINT fk_ratings_courier  FOREIGN KEY (courier_id)  REFERENCES users (id),
    CONSTRAINT ck_ratings_score    CHECK (score BETWEEN 1 AND 5)
);
CREATE INDEX ix_ratings_courier ON ratings (courier_id);

-- ---------- REFRESH TOKENS ----------
CREATE TABLE refresh_tokens (
    id          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id     NUMBER(19)        NOT NULL,
    token_hash  VARCHAR2(64 CHAR) NOT NULL,
    expires_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked     BOOLEAN DEFAULT FALSE NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_rt      PRIMARY KEY (id),
    CONSTRAINT uq_rt_hash UNIQUE (token_hash),
    CONSTRAINT fk_rt_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_rt_user ON refresh_tokens (user_id);

-- ---------- OUTBOX (event yang akan dikirim ke Kafka) ----------
CREATE TABLE outbox_events (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    aggregate_type  VARCHAR2(50 CHAR) NOT NULL,
    aggregate_id    VARCHAR2(50 CHAR) NOT NULL,
    event_type      VARCHAR2(50 CHAR) NOT NULL,
    payload         CLOB              NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    published_at    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_outbox      PRIMARY KEY (id),
    CONSTRAINT ck_outbox_json CHECK (payload IS JSON)
);
-- (published_at, id): baris dengan published_at NULL tetap ikut ter-index karena id tidak pernah null
CREATE INDEX ix_outbox_pending ON outbox_events (published_at, id);